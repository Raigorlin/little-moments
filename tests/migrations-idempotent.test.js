// Feature: jenkins-cicd-deploy, Property 28: 遷移冪等
// **Validates: Requirements 12.3**
//
// *For any* 遷移集合，對同一 Database 連續執行 Migration_Runner 兩次，第二次套用 0 個遷移、
// 結束碼 0，且 Schema 描述（information_schema 快照）與版本紀錄和第一次後完全相同。
//
// 需要 Ephemeral_Database（CAMPING_TEST_DATABASE_*，見 tests/support/pg.js）。
// 每次迭代建立獨立的 `t_<random>` schema：createTestDatabase 搭配空的遷移目錄，
// 只建立空 schema 與 schema_migrations，接著對產生的遷移集合執行兩次 runMigrations，
// 迭代結束時 DROP SCHEMA … CASCADE。
import { afterAll, beforeAll, describe, expect, test } from 'bun:test';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import fc from 'fast-check';

import { loadMigrations, runMigrations, EXIT_OK } from '../server/db/migrations.js';
import { readMigrationFiles } from '../scripts/migrate.mjs';
import { createTestDatabase, readTestDatabaseConfig, MIGRATIONS_DIR } from './support/pg.js';

// 未設定 CAMPING_TEST_DATABASE_* 時於載入時明確失敗（不靜默略過）。
readTestDatabaseConfig();

const RUNS = { numRuns: 100 };

// ── 產生器：安全的 CREATE TABLE / ADD COLUMN / CREATE INDEX 遷移 ─────────────────────────
const TYPES = {
  integer: '0',
  bigint: '0',
  text: `'x'`,
  boolean: 'false',
  timestamptz: 'now()',
};
const colSpecArb = fc.record({
  type: fc.constantFrom(...Object.keys(TYPES)),
  notNull: fc.boolean(),
  withDefault: fc.boolean(),
});
const opArb = fc.oneof(
  fc.record({ kind: fc.constant('create'), cols: fc.array(colSpecArb, { minLength: 1, maxLength: 3 }), pk: fc.boolean() }),
  fc.record({ kind: fc.constant('add'), table: fc.nat(), col: colSpecArb }),
  fc.record({ kind: fc.constant('index'), table: fc.nat(), col: fc.nat(), unique: fc.boolean() }),
);

const scenarioArb = fc.record({
  includeInitial: fc.boolean(),
  migrations: fc.array(fc.array(opArb, { minLength: 1, maxLength: 3 }), { minLength: 1, maxLength: 4 }),
  versionGaps: fc.array(fc.integer({ min: 1, max: 50 }), { minLength: 4, maxLength: 4 }),
  destructiveHeader: fc.array(fc.boolean(), { minLength: 4, maxLength: 4 }),
});

const colDef = (name, c) =>
  `${name} ${c.type}${c.notNull ? ' NOT NULL' : ''}${c.withDefault ? ` DEFAULT ${TYPES[c.type]}` : ''}`;

/** 依產生的操作序列模擬 schema 狀態，轉為合法的遷移檔（{name, content}）。 */
function buildMigrationFiles({ migrations, versionGaps, destructiveHeader }, startVersion) {
  const tables = []; // [{name, cols:[name]}]
  let tableSeq = 0, colSeq = 0, indexSeq = 0;
  let version = startVersion;
  return migrations.map((ops, i) => {
    version += versionGaps[i];
    const statements = ops.map(op => {
      if (op.kind === 'create' || tables.length === 0) {
        // 尚無資料表時，add/index 改為建立資料表（index 的 col 是索引位置，不是欄位規格）。
        const cols = op.kind === 'create' ? op.cols
          : [op.kind === 'add' ? op.col : { type: 'text', notNull: false, withDefault: false }];
        const name = `gen_tbl_${++tableSeq}`;
        const colNames = cols.map(() => `gen_col_${++colSeq}`);
        const defs = cols.map((c, k) => colDef(colNames[k], c));
        if (op.pk) defs.unshift('id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY');
        tables.push({ name, cols: colNames });
        return `CREATE TABLE ${name} (\n  ${defs.join(',\n  ')}\n);`;
      }
      const table = tables[op.table % tables.length];
      if (op.kind === 'add') {
        const col = `gen_col_${++colSeq}`;
        table.cols.push(col);
        return `ALTER TABLE ${table.name} ADD COLUMN ${colDef(col, op.col)};`;
      }
      const col = table.cols[op.col % table.cols.length];
      return `CREATE ${op.unique ? 'UNIQUE ' : ''}INDEX gen_idx_${++indexSeq} ON ${table.name} (${col});`;
    });
    // 標記只影響 schema_migrations.destructive 欄位（遷移內容本身皆為安全語句）。
    const header = destructiveHeader[i] ? '-- lm:destructive\n' : '';
    return {
      name: `${String(version).padStart(4, '0')}_gen_${i + 1}.sql`,
      content: `${header}-- generated migration ${i + 1}\n${statements.join('\n')}\n`,
    };
  });
}

// ── information_schema / pg_catalog 快照（只限目前測試 schema） ─────────────────────────
async function snapshot(sql) {
  const tables = await sql`
    SELECT table_name, table_type FROM information_schema.tables
    WHERE table_schema = current_schema() ORDER BY table_name`;
  const columns = await sql`
    SELECT table_name, column_name, ordinal_position, data_type, is_nullable, column_default,
           is_identity, identity_generation, character_maximum_length, numeric_precision
    FROM information_schema.columns
    WHERE table_schema = current_schema() ORDER BY table_name, ordinal_position`;
  const constraints = await sql`
    SELECT tc.table_name, tc.constraint_name, tc.constraint_type,
           pg_get_constraintdef(c.oid) AS definition
    FROM information_schema.table_constraints tc
    JOIN pg_constraint c ON c.conname = tc.constraint_name
    JOIN pg_namespace n ON n.oid = c.connamespace AND n.nspname = tc.constraint_schema
    WHERE tc.constraint_schema = current_schema()
    ORDER BY tc.table_name, tc.constraint_name`;
  const indexes = await sql`
    SELECT tablename, indexname, indexdef FROM pg_indexes
    WHERE schemaname = current_schema() ORDER BY tablename, indexname`;
  const sequences = await sql`
    SELECT sequence_name, data_type, start_value, increment FROM information_schema.sequences
    WHERE sequence_schema = current_schema() ORDER BY sequence_name`;
  const plain = rows => rows.map(r => ({ ...r }));
  return {
    tables: plain(tables),
    columns: plain(columns),
    constraints: plain(constraints),
    indexes: plain(indexes),
    sequences: plain(sequences),
  };
}

async function migrationRows(sql) {
  // applied_at 以文字（含微秒）比對：第二次執行不得改寫任何既有紀錄。
  const rows = await sql`
    SELECT version, name, checksum, destructive, applied_at::text AS applied_at
    FROM schema_migrations ORDER BY version`;
  return rows.map(r => ({ ...r, version: Number(r.version) }));
}

describe('Property 28: 遷移冪等', () => {
  let emptyDir;
  let initialFile;

  beforeAll(async () => {
    emptyDir = await mkdtemp(join(tmpdir(), 'lm-migrations-empty-'));
    initialFile = (await readMigrationFiles(MIGRATIONS_DIR)).find(f => f.name === '0001_initial.sql');
    if (!initialFile) throw new Error('找不到 migrations/0001_initial.sql');
  });

  afterAll(async () => {
    if (emptyDir) await rm(emptyDir, { recursive: true, force: true });
  });

  test('連續執行兩次：第二次套用 0 個、結束碼 0，Schema 快照與版本紀錄不變', async () => {
    await fc.assert(
      fc.asyncProperty(scenarioArb, async scenario => {
        const generated = buildMigrationFiles(scenario, scenario.includeInitial ? 1 : 0);
        const files = scenario.includeInitial ? [initialFile, ...generated] : generated;
        const repo = loadMigrations(files);
        const expectedVersions = repo.map(m => m.version);

        const db = await createTestDatabase({ migrationsDir: emptyDir });
        try {
          const first = await runMigrations(db.sql, repo);
          expect(first.exitCode).toBe(EXIT_OK);
          expect(first.applied).toEqual(expectedVersions);
          expect(first.count).toBe(expectedVersions.length);

          const schemaAfterFirst = await snapshot(db.sql);
          const rowsAfterFirst = await migrationRows(db.sql);
          expect(rowsAfterFirst.map(r => r.version)).toEqual(expectedVersions);
          expect(rowsAfterFirst.map(r => r.checksum)).toEqual(repo.map(m => m.checksum));
          expect(rowsAfterFirst.map(r => r.destructive)).toEqual(repo.map(m => m.destructive));

          const second = await runMigrations(db.sql, repo);
          expect(second.exitCode).toBe(EXIT_OK);
          expect(second.applied).toEqual([]);
          expect(second.count).toBe(0);
          expect(second.unknownApplied).toEqual([]);
          expect(second.checksumMismatch).toEqual([]);
          expect(second.error).toBeNull();

          expect(await snapshot(db.sql)).toEqual(schemaAfterFirst);
          expect(await migrationRows(db.sql)).toEqual(rowsAfterFirst);
        } finally {
          await db.close();
        }
      }),
      RUNS,
    );
  }, 600_000);
});

// Feature: jenkins-cicd-deploy, Property 31: 破壞性遷移偵測
// **Validates: Requirements 12.6, 12.9**
import { describe, expect, test } from 'bun:test';
import fc from 'fast-check';

import { detectDestructive, findDestructiveStatements, analyzeSql, lintMigration, DESTRUCTIVE_KINDS } from '../scripts/lint-migrations.mjs';

const RUNS = { numRuns: 200 };

const tableName = fc.constantFrom('users', 'trips', 'notes', 'public.trip_members', '"Audit Log"');
const columnName = fc.constantFrom('title', 'note', 'created_at', 'c1');

// 關鍵字之間的分隔：任意空白、換行或區塊註解。
const separator = fc.oneof(
  fc.array(fc.constantFrom(' ', '\t', '\n', '\r\n'), { minLength: 1, maxLength: 3 }).map(a => a.join('')),
  fc.constantFrom(' /* c */ ', '\n/* x /* nested */ y */\n'),
);

// 每個字元隨機大小寫（僅套用於未加引號的關鍵字與識別字）。
const randomCase = word => fc.array(fc.boolean(), { minLength: word.length, maxLength: word.length })
  .map(flags => [...word].map((ch, i) => (flags[i] ? ch.toUpperCase() : ch.toLowerCase())).join(''));

// 以 token 陣列組成語句：未加引號者隨機大小寫，雙引號識別字原樣保留。
const joinTokens = tokens => fc.tuple(
  fc.tuple(...tokens.map(t => (t.startsWith('"') || t.includes('"') ? fc.constant(t) : randomCase(t)))),
  fc.array(separator, { minLength: tokens.length, maxLength: tokens.length }),
).map(([words, seps]) => words.map((w, i) => (i === 0 ? w : seps[i] + w)).join(''));

/** 破壞性語句產生器：回傳 {kind, text}。 */
const destructiveArb = fc.oneof(
  fc.tuple(tableName, fc.boolean()).chain(([t, ifExists]) =>
    joinTokens(['DROP', 'TABLE', ...(ifExists ? ['IF', 'EXISTS'] : []), t]).map(text => ({ kind: 'drop_table', text }))),
  fc.tuple(tableName, columnName).chain(([t, c]) =>
    joinTokens(['ALTER', 'TABLE', t, 'DROP', 'COLUMN', c]).map(text => ({ kind: 'drop_column', text }))),
  fc.tuple(tableName, columnName).chain(([t, c]) =>
    joinTokens(['ALTER', 'TABLE', 'IF', 'EXISTS', 'ONLY', t, 'ADD', 'COLUMN', 'x2', 'int', ',', 'DROP', 'COLUMN', c])
      .map(text => ({ kind: 'drop_column', text }))),
  fc.tuple(tableName, columnName).chain(([t, c]) =>
    joinTokens(['ALTER', 'TABLE', t, 'DROP', c]).map(text => ({ kind: 'alter_table_drop', text }))),
  tableName.chain(t =>
    joinTokens(['ALTER', 'TABLE', t, 'DROP', 'CONSTRAINT', 'fk_owner']).map(text => ({ kind: 'alter_table_drop', text }))),
  tableName.chain(t =>
    joinTokens(['ALTER', 'TABLE', t, 'RENAME', 'TO', 'renamed']).map(text => ({ kind: 'alter_table_rename', text }))),
  fc.tuple(tableName, columnName).chain(([t, c]) =>
    joinTokens(['ALTER', 'TABLE', t, 'RENAME', 'COLUMN', c, 'TO', 'c_new']).map(text => ({ kind: 'alter_table_rename', text }))),
  joinTokens(['DROP', 'SCHEMA', 'legacy', 'CASCADE']).map(text => ({ kind: 'drop_schema', text })),
);

// 安全語句：不含 DROP／RENAME 關鍵字、不含無法在交易內執行的語句。
const safeArb = fc.constantFrom(
  'CREATE TABLE gear (id TEXT PRIMARY KEY, label TEXT NOT NULL)',
  'ALTER TABLE users ADD COLUMN nickname TEXT',
  'ALTER TABLE trips ALTER COLUMN note SET DEFAULT \'\'',
  'CREATE INDEX trips_owner ON trips(owner_id)',
  'INSERT INTO notes (id, body) VALUES (1, \'hello\')',
  'UPDATE users SET display_name = \'x\' WHERE id = \'u1\'',
  'ALTER INDEX trips_owner RENAME TO trips_owner_idx',
  'CREATE TABLE "dropped_items" (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY)',
  'COMMENT ON TABLE users IS \'帳號\'',
  'SELECT 1',
);

const dollarTag = fc.stringMatching(/^[a-z_]{0,6}$/).map(s => `$${s}$`);

/** 將破壞性文字放進註解、字串常值或雙引號識別字內（不應被偵測）。 */
const hiddenArb = fc.tuple(destructiveArb, fc.integer({ min: 0, max: 8 }), dollarTag).map(([{ text }, mode, tag]) => {
  switch (mode) {
    case 0: return `-- ${text.replace(/\r?\n/g, ' ')}\nSELECT 1`;
    case 1: return `/* ${text} */ SELECT 1`;
    case 2: return `/* outer /* ${text} */ still comment */ SELECT 1`;
    case 3: return `SELECT '${text}'`;
    case 4: return `INSERT INTO notes (body) VALUES ('it''s ${text}')`;
    case 5: return `SELECT E'it\\'s ${text}'`;
    case 6: return `SELECT $$${text}$$`;
    case 7: return `DO ${tag} BEGIN PERFORM 1; ${text}; END ${tag}`;
    default: return `CREATE TABLE "${text.replace(/"/g, '""')}" (id int)`;
  }
});

const stmtSep = fc.constantFrom(';\n', ';', ' ;\r\n\n', ';\n-- next\n');

/** 以分號串接語句，結尾隨機附加分號。 */
const script = (stmts, seps, trailing) =>
  stmts.map((s, i) => (i === 0 ? s : seps[i - 1] + s)).join('') + (trailing ? ';\n' : '');

const bodyArb = (extra = []) => fc.tuple(fc.array(fc.oneof(safeArb, hiddenArb), { maxLength: 6 }), ...extra)
  .chain(([base, ...more]) => {
    const all = [...base, ...more];
    return fc.tuple(
      all.length ? fc.shuffledSubarray(all, { minLength: all.length, maxLength: all.length }) : fc.constant([]),
      fc.array(stmtSep, { minLength: Math.max(0, all.length - 1), maxLength: Math.max(0, all.length - 1) }),
      fc.boolean(),
    ).map(([ordered, seps, trailing]) => script(ordered, seps, trailing));
  });

describe('Property 31: 破壞性遷移偵測', () => {
  test('註解與字串以外的破壞性語句一律被偵測，且類別正確', () => {
    fc.assert(fc.property(
      destructiveArb.chain(d => bodyArb([fc.constant(d.text)]).map(sql => ({ d, sql }))),
      ({ d, sql }) => {
        expect(DESTRUCTIVE_KINDS).toContain(d.kind);
        expect(detectDestructive(sql)).toBe(true);
        expect(findDestructiveStatements(sql).map(f => f.kind)).toContain(d.kind);
        expect(analyzeSql(sql).errors).toEqual([]);
      },
    ), RUNS);
  });

  test('只出現在註解、字串常值、錢號引號或雙引號識別字內的破壞性文字不被偵測', () => {
    fc.assert(fc.property(bodyArb(), sql => {
      const analysis = analyzeSql(sql);
      expect(analysis.errors).toEqual([]);
      expect(analysis.destructive).toEqual([]);
      expect(detectDestructive(sql)).toBe(false);
    }), RUNS);
  });

  test('lint 失敗若且唯若有破壞性語句但缺少標記，或含無法在交易內執行的語句', () => {
    fc.assert(fc.property(
      fc.record({
        destructive: fc.option(destructiveArb, { nil: null }),
        marked: fc.boolean(),
        extraHeader: fc.boolean(),
        nonTx: fc.boolean(),
      }).chain(c => bodyArb([
        ...(c.destructive ? [fc.constant(c.destructive.text)] : []),
        ...(c.nonTx ? [fc.constant('CREATE INDEX CONCURRENTLY notes_body ON notes (body)')] : []),
      ]).map(body => ({ ...c, body }))),
      ({ destructive, marked, extraHeader, nonTx, body }) => {
        const header = `${extraHeader ? '-- 說明：測試遷移\n\n' : ''}${marked ? '-- lm:destructive\n' : ''}`;
        const result = lintMigration({ name: '0002_test.sql', sql: header + body });
        const expected = !nonTx && (!destructive || marked);
        expect(result.ok).toBe(expected);
        expect(result.marked).toBe(marked);
        expect(result.destructive.length > 0).toBe(destructive !== null);
        expect(result.nonTransactional.length > 0).toBe(nonTx);
      },
    ), RUNS);
  });
});
